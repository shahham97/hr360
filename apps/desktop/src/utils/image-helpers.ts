/**
 * Image resizing and optimization utility (P2.3 Data Lifecycle)
 * Enforces size cap <= 200 KB for database efficiency on free tiers
 */
export async function optimizeImageUpload(file: File, maxDimension: number = 400, quality: number = 0.85): Promise<string> {
  return new Promise((resolve, reject) => {
    // If already small and valid, return data URL directly
    if (file.size <= 80 * 1024) {
      const reader = new FileReader();
      reader.onload = () => resolve(reader.result as string);
      reader.onerror = reject;
      reader.readAsDataURL(file);
      return;
    }

    const reader = new FileReader();
    reader.onload = (e) => {
      const img = new Image();
      img.onload = () => {
        let width = img.width;
        let height = img.height;

        if (width > maxDimension || height > maxDimension) {
          if (width > height) {
            height = Math.round((height * maxDimension) / width);
            width = maxDimension;
          } else {
            width = Math.round((width * maxDimension) / height);
            height = maxDimension;
          }
        }

        const canvas = document.createElement('canvas');
        canvas.width = width;
        canvas.height = height;
        const ctx = canvas.getContext('2d');
        if (!ctx) {
          resolve(e.target?.result as string);
          return;
        }

        ctx.drawImage(img, 0, 0, width, height);
        // Use webp or png
        const output = canvas.toDataURL('image/png', quality);
        resolve(output);
      };
      img.onerror = reject;
      img.src = e.target?.result as string;
    };
    reader.onerror = reject;
    reader.readAsDataURL(file);
  });
}
